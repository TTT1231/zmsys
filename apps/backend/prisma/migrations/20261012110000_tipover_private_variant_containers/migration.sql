-- 微动目录的任何结构变化（加项/隐藏/规则）都会实时改变跌倒开关今后的建档可选集——
-- 两个产品共用一张可变目录，想分道扬镳时没有退路。本次仿照旋转XK3（焊线/插线）的
-- 容器模式让跌倒开关自持：
--   1) 新建两个停用目录容器 kd-new-micro（新微动跌倒）/ kd-old-micro（老微动跌倒），
--      前缀 KDN/KDO 仅防撞号（容器不建档不出码），业务主路径走「跌倒开关」+微动开关类型；
--   2) 容器目录 = 新微动(1003)/老微动(1004) 现行目录整体复制（组结构/物料/单选语义
--      不变，物料 id 全新），此后跌倒开关与微动产品的目录互不影响、各自演进；
--   3) 1006 child_categories 改指向两个容器。存量 KD BOM 为建档冻结快照不受影响，
--      其明细仍指向微动产品目录的物料 id——前端复合分节按全量目录兜底识别系列
--      （bomComposition.ts），历史档案展示不回退。
